// Post-processes wasm-pack output so the package works without bundler config:
//
// 1. Writes wasm/text_shape_wasm_base64.js, which embeds the .wasm as base64.
//    initText() loads it with a dynamic import, so it lands in its own chunk.
// 2. Removes the glue's default `new URL("text_shape_bg.wasm", import.meta.url)`.
//    Bundlers detect that pattern and emit the .wasm as a separate asset, which
//    would ship the binary twice. It's also what breaks under Vite pre-bundling.
//
// The .wasm file itself stays in the package for callers that pass their own
// source to initText().

import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../wasm/", import.meta.url);

const wasm = readFileSync(new URL("text_shape_bg.wasm", dir));
writeFileSync(
  new URL("text_shape_wasm_base64.js", dir),
  `// Generated by scripts/embed-wasm.mjs. Do not edit.\nexport default "${wasm.toString("base64")}";\n`,
);
writeFileSync(
  new URL("text_shape_wasm_base64.d.ts", dir),
  "/** The text-shape .wasm binary, base64-encoded. */\ndeclare const wasm: string;\nexport default wasm;\n",
);

const gluePath = new URL("text_shape.js", dir);
const glue = readFileSync(gluePath, "utf8");
const defaultUrl = "module_or_path = new URL('text_shape_bg.wasm', import.meta.url);";
const count = glue.split(defaultUrl).length - 1;
if (count !== 1) {
  throw new Error(
    `embed-wasm: expected 1 default wasm URL in text_shape.js, found ${count}. ` +
      "wasm-bindgen output changed; update this script.",
  );
}
writeFileSync(
  gluePath,
  glue.replace(
    defaultUrl,
    'throw new Error("text-shape: pass a wasm source, or use initText() from \\"text-shape\\"");',
  ),
);

console.log(`embed-wasm: embedded ${(wasm.length / 1024).toFixed(0)} KB`);
